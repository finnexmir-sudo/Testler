def aheng_pozan(sozler):
    """Qalin ve ince saitleri qarisiq islenen (aheng qanununa tabe
    olmayan) sozleri qaytarir."""
    netice = []
    for w in sozler:
        saitler = [h for h in w.lower() if h in QALIN | INCE]
        if any(h in QALIN for h in saitler) and any(h in INCE for h in saitler):
            netice.append(w)
    return netice


